/** 今天露出的那一条(按天轮换,让常来的人偶尔发现新的) */
export function secretOfDay(catId: string, day: number): string | null {
  const list = CAT_SECRETS[catId];
  if (!list?.length) return null;
  return pick(mulberry32(hashSeed(day, "secret", catId)), list);
}

